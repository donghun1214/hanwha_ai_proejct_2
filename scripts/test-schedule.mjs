import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';

const source = fs.readFileSync('app/api/schedule/recommend/route.ts', 'utf8').replace("import { NextResponse } from 'next/server';", 'const NextResponse = Response;');
const code = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const { POST } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
process.env.OPENAI_API_KEY = 'mock-only';
const task = {id:1,name:'점검',location:'inside',duration:2,requiredCrew:1,priority:1,minSkill:3};
const input = {tasks:[task],weatherSlots:[{time:'09:00',temp:25,feelsLike:25,humidity:50,rain:0,wind:2}],workers:[{id:1,name:'테스트',level:5}],totalCrew:1};
const item = {taskId:1,startTime:'09:00',endTime:'10:00',decision:'진행',riskScore:10,reason:'기상, 인원, 작업시간 검토',assignedWorkerIds:[1]};
let result = {summary:'요약',items:{1:item}};
let calls = 0;
globalThis.fetch = async (_url, options) => {
  calls++;
  const schema = JSON.parse(options.body).text.format.schema;
  assert.deepEqual(schema.properties.items.required, input.tasks.map((task) => String(task.id)));
  assert.deepEqual(schema.properties.items.properties['1'].properties.startTime.enum, ['09:00']);
  assert.deepEqual(schema.properties.items.properties['1'].properties.taskId.enum, [1]);
  return Response.json({output:[{content:[{type:'output_text',text:JSON.stringify(result)}]}]});
};
const run = async (body = input) => POST(new Request('http://localhost/api/schedule/recommend',{method:'POST',body:JSON.stringify(body)}));
assert.equal((await run()).status,200);
assert.equal((await (await run()).json()).items[0].endTime,'11:00');
result = {summary:'요약',items:{1:{...item,startTime:' 9:00 '}}};
assert.equal((await (await run()).json()).items[0].startTime,'09:00');
result = {summary:'요약',items:{1:{...item,startTime:'12:00'}}};
assert.match((await (await run()).json()).message,/시작 시간/);
result = {summary:'요약',items:{1:{...item,riskScore:101}}};
assert.match((await (await run()).json()).message,/위험 점수/);
result = {summary:'요약',items:{}};
assert.match((await (await run()).json()).message,/작업 수/);
input.tasks.push({...task,id:2});
result = {summary:'요약',items:{1:item,2:{...item,taskId:2}}};
const parallel = (await (await run()).json()).items;
assert.deepEqual(parallel[0].assignedWorkerIds,[1]);
assert.deepEqual(parallel[1].assignedWorkerIds,[]);
assert.equal(parallel[1].decision,'중단 검토');
const before = calls;
assert.equal((await run({...input,tasks:[{...task,duration:10}]})).status,400);
assert.equal(calls,before);
console.log('PASS: schema constraints, duration, time normalization, invalid time/risk, missing task, overlapping workers, impossible duration');
